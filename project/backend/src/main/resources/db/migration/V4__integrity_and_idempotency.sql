-- Canonical idempotency: one row per (scope, key), carrying the request fingerprint
-- and the original serialized response. Status ACTIVE means the business work is
-- still in flight. COMPLETED means response_json is safe to replay.
CREATE TABLE idempotency_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope VARCHAR(48) NOT NULL,
    "key" VARCHAR(120) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','COMPLETED')),
    response_json TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_idempotency_scope_key UNIQUE (scope, "key")
);

-- PostgreSQL partial indexes and H2 do not share syntax. A nullable column plus a
-- CHECK gives the same invariant on both engines: only ACTIVE reservations occupy
-- a blood_unit_id slot in this sparse unique index (NULLs are not indexed).
ALTER TABLE reservations ADD COLUMN active_unit_id BIGINT;
UPDATE reservations SET active_unit_id = blood_unit_id WHERE status = 'ACTIVE';
CREATE UNIQUE INDEX uq_active_reservation_per_unit ON reservations(active_unit_id);
-- A row may briefly have a NULL slot inside its creating transaction (JPA inserts
-- the entity before the companion UPDATE), but any populated slot must belong to
-- an ACTIVE reservation for that exact unit and must be cleared on lifecycle exit.
ALTER TABLE reservations ADD CONSTRAINT chk_reservation_active_unit CHECK (
    active_unit_id IS NULL OR (status = 'ACTIVE' AND active_unit_id = blood_unit_id)
);

-- Align the unit aggregate with its active reservation pointer. Stale pointers on
-- terminal units are cleared first so the migration is safe on existing data.
UPDATE blood_units SET active_reservation_id = NULL
WHERE active_reservation_id IS NOT NULL AND status <> 'RESERVED';
ALTER TABLE blood_units ADD CONSTRAINT chk_unit_reserved_has_active_reservation CHECK (
    status <> 'RESERVED' OR active_reservation_id IS NOT NULL
);
ALTER TABLE blood_units ADD CONSTRAINT chk_unit_active_reservation_status CHECK (
    active_reservation_id IS NULL OR status IN ('RESERVED','DISPATCHED')
);

CREATE TABLE donor_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    blood_group VARCHAR(20) NOT NULL,
    date_of_birth DATE,
    address VARCHAR(240),
    city VARCHAR(100),
    state VARCHAR(100),
    preferred_contact VARCHAR(24) NOT NULL DEFAULT 'IN_APP',
    availability VARCHAR(24) NOT NULL DEFAULT 'AVAILABLE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    donor_id BIGINT NOT NULL REFERENCES donor_profiles(id) ON DELETE CASCADE,
    type VARCHAR(60) NOT NULL,
    granted BOOLEAN NOT NULL,
    granted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    withdrawn_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_consent_donor ON consents(donor_id);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    donor_id BIGINT NOT NULL REFERENCES donor_profiles(id) ON DELETE CASCADE,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    scheduled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'REQUESTED'
        CHECK (status IN ('REQUESTED','CONFIRMED','COMPLETED','CANCELLED','REJECTED')),
    notes VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_appointment_donor ON appointments(donor_id, scheduled_at DESC);
CREATE INDEX idx_appointment_org ON appointments(organization_id, scheduled_at DESC);

CREATE TABLE donations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    donor_id BIGINT NOT NULL REFERENCES donor_profiles(id),
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    appointment_id BIGINT REFERENCES appointments(id),
    donated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'RECORDED'
        CHECK (status IN ('RECORDED','SCREENED','APPROVED','REJECTED')),
    notes VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_donation_donor ON donations(donor_id, donated_at DESC);
CREATE INDEX idx_donation_org ON donations(organization_id, donated_at DESC);

CREATE TABLE screening_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    donation_id BIGINT NOT NULL REFERENCES donations(id) ON DELETE CASCADE,
    passed BOOLEAN NOT NULL,
    notes VARCHAR(500),
    screened_by BIGINT NOT NULL REFERENCES users(id),
    screened_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE storage_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    code VARCHAR(40) NOT NULL,
    name VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_storage_code UNIQUE (organization_id, code)
);

CREATE TABLE blood_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    unit_number VARCHAR(60) NOT NULL UNIQUE,
    blood_group VARCHAR(20) NOT NULL,
    component_type VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'COLLECTED'
        CHECK (status IN ('COLLECTED','SCREENING','QUARANTINED','AVAILABLE','RESERVED','DISPATCHED','DELIVERED','EXPIRED','DISCARDED')),
    released BOOLEAN NOT NULL DEFAULT FALSE,
    collected_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    storage_location VARCHAR(120) NOT NULL,
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    donation_id BIGINT REFERENCES donations(id),
    active_reservation_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_expiry_after_collection CHECK (expires_at > collected_at)
);
CREATE INDEX idx_unit_org_status ON blood_units(organization_id, status);
CREATE INDEX idx_unit_expiry ON blood_units(expires_at, status);
CREATE INDEX idx_unit_group_component ON blood_units(blood_group, component_type, status, expires_at);

CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    unit_id BIGINT NOT NULL REFERENCES blood_units(id) ON DELETE CASCADE,
    from_status VARCHAR(32),
    to_status VARCHAR(32) NOT NULL,
    reason VARCHAR(240) NOT NULL,
    actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_movement_unit ON inventory_movements(unit_id, occurred_at DESC);

CREATE TABLE emergency_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    request_number VARCHAR(40) NOT NULL UNIQUE,
    requesting_org_id BIGINT NOT NULL REFERENCES organizations(id),
    patient_ref VARCHAR(80),
    blood_group VARCHAR(20) NOT NULL,
    component_type VARCHAR(32) NOT NULL,
    quantity INT NOT NULL CHECK (quantity > 0 AND quantity <= 99),
    priority VARCHAR(16) NOT NULL DEFAULT 'ROUTINE'
        CHECK (priority IN ('ROUTINE','URGENT','CRITICAL')),
    required_by TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT','PENDING_VERIFICATION','VERIFIED','APPROVED','ALLOCATING','RESERVED','IN_TRANSIT','FULFILLED','REJECTED','CANCELLED','EXPIRED')),
    reason VARCHAR(1000),
    created_by BIGINT NOT NULL REFERENCES users(id),
    verified_by BIGINT REFERENCES users(id),
    approved_by BIGINT REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_request_org_status ON emergency_requests(requesting_org_id, status, created_at DESC);
CREATE INDEX idx_request_priority ON emergency_requests(priority, required_by);

CREATE TABLE request_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    request_id BIGINT NOT NULL REFERENCES emergency_requests(id) ON DELETE CASCADE,
    action VARCHAR(80) NOT NULL,
    notes VARCHAR(500),
    actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_request_event_request ON request_events(request_id, occurred_at DESC);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    blood_unit_id BIGINT NOT NULL REFERENCES blood_units(id),
    request_id BIGINT NOT NULL REFERENCES emergency_requests(id),
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE','CONFIRMED','CANCELLED','EXPIRED')),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at TIMESTAMP WITH TIME ZONE,
    idempotency_key VARCHAR(120) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_reservation_org_status ON reservations(organization_id, status, expires_at);
CREATE INDEX idx_reservation_request ON reservations(request_id);

ALTER TABLE blood_units ADD CONSTRAINT fk_unit_active_reservation
    FOREIGN KEY (active_reservation_id) REFERENCES reservations(id);
CREATE UNIQUE INDEX uq_unit_active_reservation ON blood_units(active_reservation_id);

CREATE TABLE dispatches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    reservation_id BIGINT NOT NULL UNIQUE REFERENCES reservations(id),
    request_id BIGINT NOT NULL REFERENCES emergency_requests(id),
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    assigned_staff VARCHAR(160) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PREPARING'
        CHECK (status IN ('PREPARING','IN_TRANSIT','DELIVERED','INCIDENT')),
    dispatched_at TIMESTAMP WITH TIME ZONE,
    delivered_at TIMESTAMP WITH TIME ZONE,
    recipient_name VARCHAR(160),
    incident_description VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_dispatch_org_status ON dispatches(organization_id, status, created_at DESC);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(160) NOT NULL,
    body VARCHAR(1000) NOT NULL,
    type VARCHAR(60) NOT NULL,
    channel VARCHAR(30) NOT NULL DEFAULT 'IN_APP',
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','SENT','FAILED')),
    read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_notification_user ON notifications(user_id, created_at DESC);

CREATE TABLE outbox_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL UNIQUE,
    event_id VARCHAR(36) NOT NULL UNIQUE,
    topic VARCHAR(100) NOT NULL,
    payload VARCHAR(4000) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','PROCESSING','PROCESSED','FAILED')),
    attempts INT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_outbox_pending ON outbox_events(status, next_attempt_at);
